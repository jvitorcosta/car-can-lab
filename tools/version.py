"""Firmware version from git (semantic versioning): writes include/fw_version.h before a build.

Releases are tags vMAJOR.MINOR.PATCH (README "Versioning"). `git describe --tags --dirty` gives:
  v1.2.0                  -> 1.2.0                (short 1.2.0)
  v1.2.0-3-gabc1234       -> 1.2.0+3.gabc1234     (short 1.2.0+)
  v1.2.0-dirty            -> 1.2.0+dirty          (short 1.2.0+)
  no tag (shallow clone)  -> 0.0.0-dev+gabc1234   (short 0.0.0-dev)
The header is rewritten only when the version changes, so it doesn't force a rebuild.

  python tools/version.py          print the version
"""
import os
import re
import subprocess

try:   # PlatformIO pre: script (SCons provides Import; __file__ isn't defined there)
    Import("env")  # noqa: F821
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
    UNDER_PIO = True
except NameError:
    ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    UNDER_PIO = False
OUT = os.path.join(ROOT, "include", "fw_version.h")
TAG = re.compile(r"^v(\d+\.\d+\.\d+)(?:-(\d+)-(g[0-9a-f]+))?(-dirty)?$")


def from_describe(desc, sha):
    """(full, short) for `git describe --tags --dirty` output (None when it failed)."""
    m = TAG.match(desc or "")
    if not m:
        return ("0.0.0-dev+" + sha if sha else "0.0.0-dev"), "0.0.0-dev"
    core, ahead, commit, dirty = m.groups()
    meta = ([ahead, commit] if ahead else []) + (["dirty"] if dirty else [])
    return (core + "+" + ".".join(meta) if meta else core), (core + "+" if meta else core)


def _git(*args):
    try:
        return subprocess.run(["git"] + list(args), cwd=ROOT, capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def current():
    sha = _git("rev-parse", "--short", "HEAD")
    return from_describe(_git("describe", "--tags", "--dirty", "--match", "v[0-9]*"),
                         "g" + sha if sha else None)


def write_header():
    full, short = current()
    text = ("// Generated by tools/version.py from git describe. Do not edit or commit.\n"
            "#pragma once\n#define FW_VERSION \"%s\"\n#define FW_VERSION_SHORT \"%s\"\n" % (full, short))
    old = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else None
    if old != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("version: %s" % full)


if UNDER_PIO:
    write_header()
elif __name__ == "__main__":
    print(current()[0])
